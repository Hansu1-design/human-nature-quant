def cluster_ids(sig, cool=COOL_DAYS):
    """把 11 笔按「与上一独立轮首笔间隔 > cool 日」归成 6 轮。
    ★ 这是 R53 d188 §6 已定的口径，本轮不新造代表取法。"""
    out, last, cid = [], -10**9, -1
    for a in sig:
        if a - last > cool:
            cid += 1
            last = a
        out.append(cid)
    return out


def holm(pvals, m=None):
    """Holm 校正，返回校正后 p 数组（与输入同序）。"""
    import numpy as np
    p = np.asarray(pvals, dtype=float)
    m = len(p) if m is None else m
    order = np.argsort(p)
    adj = np.empty_like(p)
    run = 0.0
    for rank, i in enumerate(order):
        v = min(1.0, p[i] * (m - rank))
        run = max(run, v)
        adj[i] = run
    return adj


